const root = document.documentElement;
const aura = document.querySelector(".cursor-aura");
const header = document.querySelector("[data-elevate]");
const copyToast = document.querySelector(".copy-toast");
const reduceMotion = window.matchMedia("(prefers-reduced-motion: reduce)").matches;
let currentLanguage = "ja";
let toastTimer;

function setLanguage(lang) {
  const dictionary = translations[lang] || translations.ja;
  currentLanguage = translations[lang] ? lang : "ja";
  root.lang = lang === "ko" ? "ko" : lang === "en" ? "en" : "ja";
  document.querySelectorAll("[data-i18n]").forEach((node) => {
    const value = dictionary[node.dataset.i18n];
    if (value) node.innerHTML = value;
  });
  document.querySelectorAll(".lang-button").forEach((button) => button.classList.toggle("active", button.dataset.lang === lang));
  localStorage.setItem("portfolio-language", lang);
}

document.querySelectorAll(".lang-button").forEach((button) => button.addEventListener("click", () => setLanguage(button.dataset.lang)));

async function copyEmail() {
  const email = "kim93yohan@gmail.com";
  try {
    await navigator.clipboard.writeText(email);
  } catch {
    const input = document.createElement("textarea");
    input.value = email;
    input.setAttribute("readonly", "");
    input.style.position = "fixed";
    input.style.opacity = "0";
    document.body.appendChild(input);
    input.select();
    document.execCommand("copy");
    input.remove();
  }

  if (!copyToast) return;
  copyToast.textContent = translations[currentLanguage].emailCopied;
  copyToast.classList.add("is-visible");
  window.clearTimeout(toastTimer);
  toastTimer = window.setTimeout(() => copyToast.classList.remove("is-visible"), 2200);
}

document.querySelectorAll("[data-copy-email]").forEach((button) => button.addEventListener("click", copyEmail));

document.querySelectorAll("[data-project-href]").forEach((card) => {
  card.addEventListener("click", (event) => {
    if (event.target.closest("a, button")) return;
    window.location.href = card.dataset.projectHref;
  });
});

const landingNavLinks = [...document.querySelectorAll('.nav-links a[href^="#"]')];
const landingNavSections = landingNavLinks
  .map((link) => ({ link, section: document.querySelector(link.getAttribute("href")) }))
  .filter(({ section }) => section);

function updateLandingNavigation() {
  if (!landingNavSections.length) return;
  const marker = window.scrollY + (header?.offsetHeight || 66) + window.innerHeight * 0.22;
  let current = landingNavSections[0];
  landingNavSections.forEach((item) => {
    if (item.section.offsetTop <= marker) current = item;
  });
  landingNavSections.forEach(({ link }) => {
    const active = link === current.link;
    link.classList.toggle("is-active", active);
    if (active) link.setAttribute("aria-current", "location");
    else link.removeAttribute("aria-current");
  });
}

if (reduceMotion) {
  document.querySelectorAll(".reveal").forEach((node) => node.classList.add("is-visible"));
} else {
  const observer = new IntersectionObserver((entries) => {
    entries.forEach((entry) => {
      if (entry.isIntersecting) {
        entry.target.classList.add("is-visible");
        observer.unobserve(entry.target);
      }
    });
  }, { threshold: 0.1, rootMargin: "0px 0px -8% 0px" });
  document.querySelectorAll(".reveal").forEach((node) => observer.observe(node));
}

window.addEventListener("scroll", () => {
  header?.classList.toggle("is-scrolled", window.scrollY > 16);
  updateLandingNavigation();
}, { passive: true });
window.addEventListener("pointermove", (event) => {
  if (!aura || reduceMotion) return;
  aura.style.opacity = "1";
  aura.style.left = `${event.clientX}px`;
  aura.style.top = `${event.clientY}px`;
});

document.querySelectorAll(".magnetic").forEach((node) => {
  node.addEventListener("pointermove", (event) => {
    const rect = node.getBoundingClientRect();
    node.style.transform = `translate(${(event.clientX - rect.left - rect.width / 2) * 0.05}px, ${(event.clientY - rect.top - rect.height / 2) * 0.08}px)`;
  });
  node.addEventListener("pointerleave", () => { node.style.transform = ""; });
});

setLanguage(localStorage.getItem("portfolio-language") || "ja");
updateLandingNavigation();
